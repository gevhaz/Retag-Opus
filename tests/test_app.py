    mock_show.side_effect = [0, 0, 0, 2, None]

    monkeypatch.setattr(oggopus.OggOpus, "__init__", lambda *_: None)
    monkeypatch.setattr(oggopus.OggOpus, "items", lambda *_: metadata)
