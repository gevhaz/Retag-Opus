def create_silent_opus_file(path: Path) -> None:
    """Write one second of silence encoded as opus to path using ffmpeg."""
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-loglevel",
            "error",
            "-f",
            "lavfi",
            "-i",
            "anullsrc=r=48000:cl=mono",
            "-t",
            "1",
            "-c:a",
            "libopus",
            str(path),
        ],
        check=True,
    )


