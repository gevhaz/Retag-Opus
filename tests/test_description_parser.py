"""Tests for description_parser.py."""
from retag_opus import description_parser


def test_parse_credits() -> None:
    """Credits are put in tags named as on MusicBrainz."""
    tags = description_parser.parse(
        "Provided to YouTube by Label\n"
        "\n"
        "Song · Singer\n"
        "\n"
        "Album\n"
        "\n"
        "Lead Vocal: Singer\n"
        "Background Vocal: Choir\n"
        "Drums: Drummer\n"
        "Lyricist: Poet\n"
        "Writer: Song Smith\n"
    )
    assert tags["performer:lead vocals"] == ["Singer"]
    assert tags["performer:background vocals"] == ["Choir"]
    assert tags["performer:drums (drum set)"] == ["Drummer"]
    assert tags["lyricist"] == ["Poet"]
    assert tags["writer"] == ["Song Smith"]


AUTO_GENERATED_DESCRIPTION = (
    "Provided to YouTube by Label\n"
    "\n"
    "Song · Singer\n"
    "\n"
    "Album\n"
    "\n"
    "℗ 2020 Label\n"
    "\n"
    "Released on: 2020-01-01\n"
    "\n"
    "Associated  Performer, Vocals: Singer\n"
    "Associated  Performer, Backing  Vocals: Choir\n"
    "Associated  Performer, Programming: Program Mer\n"
    "Composer  Lyricist: Song Smith\n"
    "Studio  Personnel, Mastering  Engineer: Mas Ter\n"
    "Lacquer Cut: Cut Ter\n"
    "Studio  Personnel, Mastering  Engineer: Other Mas Ter\n"
    "\n"
    "Auto-generated by YouTube.\n"
)


def test_parse_auto_generated_credits() -> None:
    """Credits of auto-generated descriptions are read by their roles."""
    tags = description_parser.parse(AUTO_GENERATED_DESCRIPTION)
    assert tags["title"] == ["Song"]
    assert tags["album"] == ["Album"]
    assert tags["date"] == ["2020-01-01"]
    assert tags["performer:lead vocals"] == ["Singer"]
    assert tags["performer:background vocals"] == ["Choir"]
    assert tags["composer"] == ["Song Smith"]
    assert tags["lyricist"] == ["Song Smith"]
    # Programming isn't an instrument
    assert "performer:programming" not in tags
    # An associated performer with a role isn't also a plain performer
    assert "performer" not in tags
    # Roles with no tag are left out
    assert "engineer" not in tags


def test_parse_credits_in_other_descriptions() -> None:
    """Lines with known roles are read in descriptions that aren't auto-generated."""
    tags = description_parser.parse(
        "Guitar: Gui Tarist\n"
        "Electric Guitar: Elec Tric\n"
        "Drum Programming: Program Mer\n"
        "Makeup Artist: Make Up\n"
        "Follow us: https://example.com\n"
    )
    assert tags == {"performer:guitar": ["Gui Tarist"], "performer:electric guitar": ["Elec Tric"]}


def test_parse_auto_generated_part_in_uploader_text() -> None:
    """An auto-generated part pasted among other text is parsed by its layout."""
    tags = description_parser.parse(
        "Our new video of “Other Song” by Singer from ‘Other Album’!\n"
        "\n" + AUTO_GENERATED_DESCRIPTION + "\n"
        "Guitar: Gui Tarist\n"
        "Follow us: https://example.com\n"
    )
    assert tags["organization"] == ["Label"]
    # The auto-generated part has the title and album of the song
    assert tags["title"] == ["Song"]
    assert tags["album"] == ["Album"]
    # Tags only in the uploader's text are used too
    assert tags["performer:guitar"] == ["Gui Tarist"]


def test_parse_changed_copy_of_auto_generated_description() -> None:
    """A copy whose lines were joined is read as the uploader's text."""
    tags = description_parser.parse(
        "Provided to YouTube by Label Song · Singer Album ℗ 2020 Label Released on: 2020-01-01 "
        "Auto-generated by YouTube.\n"
    )
    assert tags == {}


def test_parse_uploader_text() -> None:
    """Some common sentences are read in the uploader's text."""
    tags = description_parser.parse("Listen to “Song” by Singer from ‘Album’\n")
    assert tags == {"title": ["Song"], "artist": ["Singer"], "albumartist": ["Singer"], "album": ["Album"]}


def test_parse_manual_album() -> None:
    """With a manually set album, the album is the disc subtitle."""
    tags = description_parser.parse(AUTO_GENERATED_DESCRIPTION, manual_album_set=True)
    assert tags["discsubtitle"] == ["Album"]
    assert "album" not in tags
    tags = description_parser.parse("Listen to “Song” by Singer from ‘Album’\n", manual_album_set=True)
    assert tags["discsubtitle"] == ["Album"]
    assert "album" not in tags
